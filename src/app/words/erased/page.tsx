import Page from "../../ui/Page";

const title = "Evince Me and Let Go";

const content = `
she hides
contingent on mortar mullways,
bricklaid Tuesdays,
the smeared reminder of malted maroon heartspittle
draining through shrouded grates

who took the word "affable" from her?
Or "imposing"? Or "indifferent"?
what permits that alloyed fist to ravage
typewriter dialect
as our street corner erodes fast?

perhaps it's better to alight
this shrew erudite; set her
zanning, tanning, bobbing
through frenzy's trance in a big city seizure
until their abrasive words
leave her
glassy glossy
`;

export default function Poem() {
  return <Page title={title} content={content} />;
}
